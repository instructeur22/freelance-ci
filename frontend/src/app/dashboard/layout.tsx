export default function DashboardLayout({ children }: { children: React.ReactNode }) {
  const { user, isLoading } = useAuth();
  const pathname = usePathname();
  const router = useRouter();
  const [sidebarOpen, setSidebarOpen] = useState(false);

  useEffect(() => {
    if (!isLoading && !user) {
      router.push("/auth/login");
    }
  }, [user, isLoading, router]);

  if (isLoading || !user) {
    return <div className="flex items-center justify-center min-h-[60vh]"><span className="loading loading-spinner loading-lg text-primary" /></div>;
  }

  const links = user.role === "admin" ? adminLinks : user.role === "freelance" ? freelanceLinks : clientLinks;

  return (
    <div className="drawer lg:drawer-open">
      <input id="dashboard-drawer" type="checkbox" className="drawer-toggle" checked={sidebarOpen} onChange={() => setSidebarOpen(!sidebarOpen)} />

      <div className="drawer-content flex flex-col bg-base-200">
        <div className="lg:hidden flex items-center gap-3 p-3 border-b border-base-300 bg-base-100">
          <label htmlFor="dashboard-drawer" className="btn btn-ghost btn-sm btn-square">
            <svg xmlns="http://www.w3.org/2000/svg" className="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M4 6h16M4 12h16M4 18h16" />
            </svg>
          </label>
          <span className="font-semibold text-sm">Menu</span>
        </div>
        <div className="p-4 lg:p-8">{children}</div>
      </div>

      <div className="drawer-side z-40">
        <label htmlFor="dashboard-drawer" className="drawer-overlay" />
        <aside className="bg-base-100 border-r border-base-300 min-h-full w-72 p-4 flex flex-col gap-4">
          <div className="flex items-center gap-3 px-2 py-2">
            <img src="/Freelance-CI.jpeg" alt="Freelance CI" width={36} height={36} className="rounded-lg" />
            <div className="flex-1 min-w-0">
              <p className="font-medium text-sm truncate">{user.first_name} {user.last_name}</p>
              <p className="text-xs text-base-content/50 capitalize">
                {user.role === "admin" ? "Administrateur" : user.role === "freelance" ? "Freelance" : "Client"}
              </p>
            </div>
          </div>

          <div className="divider my-0" />

          <nav className="flex-1 overflow-y-auto">
            <ul className="menu gap-0.5">
              {links.map((link) => {
                const isActive = pathname === link.href;
                return (
                  <li key={link.href}>
                    <Link
                      href={link.href}
                      className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-colors ${
                        isActive ? "bg-primary text-primary-content font-medium shadow-sm" : "hover:bg-base-200 text-base-content"
                      }`}
                      onClick={() => setSidebarOpen(false)}
                    >
                      <svg xmlns="http://www.w3.org/2000/svg" className="w-5 h-5 shrink-0" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                        <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d={link.icon} />
                      </svg>
                      {link.label}
                    </Link>
                  </li>
                );
              })}
            </ul>
          </nav>

          <div className="divider my-0" />

          <Link href="/" className="btn btn-ghost btn-sm justify-start gap-3">
            <svg xmlns="http://www.w3.org/2000/svg" className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M10 19l-7-7m0 0l7-7m-7 7h18" />
            </svg>
            Retour au site
          </Link>
        </aside>
      </div>
    </div>
  );
}
